def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def depiction_svg(smiles, label="", width=300, height=210):
    """2D structure drawn from the docked SMILES, themed for the page.

    RDKit hard-codes black for the carbon skeleton, which disappears on the dark
    theme, and paints an opaque white background rect that would sit as a white
    block inside a dark panel. Both are stripped here: the background is removed
    and every black stroke/fill becomes `currentColor`, so the skeleton follows
    the panel's text colour in whichever theme is active."""
    from rdkit import Chem
    from rdkit.Chem import rdDepictor
    from rdkit.Chem.Draw import rdMolDraw2D

    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return ""
    rdDepictor.Compute2DCoords(mol)
    rdDepictor.StraightenDepiction(mol)
    drawer = rdMolDraw2D.MolDraw2DSVG(width, height)
    opts = drawer.drawOptions()
    opts.clearBackground = False
    opts.bondLineWidth = 1.5
    opts.multipleBondOffset = 0.14
    opts.padding = 0.06
    rdMolDraw2D.PrepareAndDrawMolecule(drawer, mol)
    drawer.FinishDrawing()
    svg = drawer.GetDrawingText()

    svg = re.sub(r"<rect[^>]*>\s*", "", svg, count=1)          # opaque background
    svg = svg.replace("<?xml version='1.0' encoding='iso-8859-1'?>", "").strip()
    svg = re.sub(r"(stroke|fill):#000000", r"\1:currentColor", svg)
    svg = svg.replace("stroke:#000000", "stroke:currentColor")
    svg = svg.replace("<svg ", '<svg class="mol2d" role="img" ', 1)
    # role="img" without an accessible name announces as a bare "image"; with 27
    # depictions on the page that is 27 meaningless stops for a screen reader.
    if label:
        svg = re.sub(r"(<svg\b[^>]*>)", r"\1<title>2D structure of " + html.escape(label) + "</title>",
                     svg, count=1)
    return svg


def viewer_block(key, label, has_poster, structure_key=None):
    """An interactive 3D viewer, with the static PyMOL render underneath it as
    the no-JavaScript fallback. The render is inside <noscript> rather than
    being replaced at runtime, so a reader without JS still sees the structure
    and a reader with JS never downloads the image."""
    structure_key = structure_key or key
    poster = (
        f'<noscript><img class="v3d-poster" src="img/{key}.png" width="620" height="460"'
        f' alt="{html.escape(label)} of {html.escape(key)}: CRBN in teal, PPIL4 in indigo,'
        f' ligand in ochre at the interface."></noscript>'
    ) if has_poster else ""
    return (
        f'<figure class="v3d">'
        f'<div class="v3d-host" data-structure="{html.escape(structure_key)}">'
        f'<p class="v3d-msg">Loading 3D model&hellip;</p></div>{poster}'
        f'<figcaption><b>{html.escape(label)}.</b> CRBN <span class="sw-c"></span>, '
        f'PPIL4 <span class="sw-p"></span>, ligand <span class="sw-l"></span>. '
        f'<span class="v3d-help">Drag to rotate &middot; scroll to zoom &middot; double-click to '
        f'reset &middot; arrow keys when focused.</span> Every structure is superposed on CRBN, so '
        f'PPIL4&rsquo;s position is comparable between them.</figcaption></figure>'
    )


def fmt(value, digits=None, dash="&mdash;"):
    if value in (None, "", "-"):
        return dash
    if digits is None:
        return html.escape(str(value))
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return html.escape(str(value))


def rule_pill(passed, label):
    state = "ok" if passed == "yes" else "no"
    mark = "&check;" if passed == "yes" else "&times;"
    return f'<span class="pill p-{state}"><b>{mark}</b>{label}</span>'



"""
Build the per-candidate detail panels for the project page and inject them into
CRBN_Project_site/index.html between its marker comments.

Each panel carries, for one molecule: a 2D depiction drawn from the exact SMILES
that was docked, the PyMOL render of its rank-1 ternary model (produced by 13),
and every measured number the pipeline produced for it -- docking, structure,
upstream pose, registry identity, and the three decision rules.

WHY THIS IS GENERATED RATHER THAN WRITTEN BY HAND. There are 20 molecules and
roughly 25 numbers each. Hand-transcribing 500 figures into HTML is not a task
with a good error rate, and every one of them already exists in a CSV. The page's
prose stays hand-written; only the panels are generated, and they are rebuilt
from the CSVs whenever the pipeline reruns.

The 2D depictions are post-processed so carbon skeletons inherit the page's text
colour via `currentColor` instead of being hard-coded black -- otherwise they
would be near-invisible against the dark theme. Heteroatoms keep RDKit's element
colours, which read on both grounds.

Run with the SYSTEM python (needs rdkit), after 11, 12 and 13:
    /Library/Frameworks/Python.framework/Versions/3.12/bin/python3 \
        "14_build_candidate_panels_(Ryan).py"
"""

def stamp_asset_versions(page):
    """Point the script tag at content-hashed URLs for viewer.js and
    structures.json.

    index.html changes on every rebuild so browsers re-fetch it, but the two
    asset files are separate requests and get served from cache -- which is how
    a rebuilt page ends up running the previous viewer against the previous
    data. Worse, a cached viewer paired with a rebuilt schema silently draws
    nothing rather than failing loudly. Hashing the contents into the query
    string makes the URL change exactly when the file does."""
    def digest(path):
        if not os.path.exists(path):
            return "0"
        with open(path, "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()[:10]

    viewer_v = digest(os.path.join(SITE_DIR, "viewer.js"))
    data_v = digest(os.path.join(SITE_DIR, "structures.json"))
    # One version for the whole lib/ directory: three.js and its two loaders are
    # only ever upgraded together, so a single stamp is enough and keeps the tag
    # readable. Mesh URLs carry their own hash, stamped by 16.
    lib_v = hashlib.sha256(b"".join(
        open(os.path.join(SITE_DIR, "lib", n), "rb").read()
        for n in sorted(os.listdir(os.path.join(SITE_DIR, "lib")))
        if n.endswith(".js")
    )).hexdigest()[:10] if os.path.isdir(os.path.join(SITE_DIR, "lib")) else "0"
    tag = (f'<script src="viewer.js?v={viewer_v}" '
           f'data-structures="structures.json?v={data_v}" '
           f'data-lib="lib" data-libv="{lib_v}" defer></script>')
    page, n = re.subn(r'<script src="viewer\.js[^"]*"[^>]*></script>', tag, page)
    if not n:
        page = page.replace("</body>", tag + "\n\n</body>", 1)
    print(f"  assets stamped: viewer.js?v={viewer_v}, structures.json?v={data_v}")
    return page


def inject(page, start, end, body, what):
    if start not in page or end not in page:
        sys.exit(f"Marker comments for {what} not found. Expected:\n  {start}\n  {end}")
    head, rest = page.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{body}\n{end}{tail}"


def main():
    rows = [r for r in read_csv(BUY_LIST) if r["role"] in ("candidate", "crosscheck")]
    if not rows:
        sys.exit(f"No candidates in {os.path.basename(BUY_LIST)} -- run 11 first.")
    rows.sort(key=lambda r: float(r["haddock_mean_best10"]))

    extras = {r["name"]: r for r in read_csv(ANNOTATED)}
    dockq = {}
    for path in (FINALISTS, CROSSCHECK):
        for r in read_csv(path):
            dockq[r["molecule"]] = r.get("dockq_vs_9dwv", "")

    missing_img = [r["name"] for r in rows if not os.path.exists(os.path.join(IMG_DIR, f"{r['name']}.png"))]
    if missing_img:
        print(f"NOTE: no render for {', '.join(missing_img)} -- run 13 under PyMOL first.")

    panels = "\n".join(panel(r, extras.get(r["name"], {}), dockq.get(r["run_name"], "")) for r in rows)

    # Controls: SMILES come from the buy list where present, and from
    # CONTROL_META for FPFT-2216, which is docked but never bought (it is not
    # commercially available) so it has no buy-list row.
    buy_smiles = {r["name"]: r["smiles"] for r in read_csv(BUY_LIST)}
    control_rows = read_csv(CONTROLS_CSV)
    controls_html = []
    for row in sorted(control_rows, key=lambda r: float(r["mean_best_10"] or 0)):
        meta = CONTROL_META.get(row["molecule"])
        if meta is None:
            print(f"NOTE: no description for control {row['molecule']} -- skipped")
            continue
        smiles = meta["smiles"] or buy_smiles.get(row["molecule"], "")
        if not smiles:
            print(f"NOTE: no SMILES for control {row['molecule']} -- 2D structure omitted")
        has_img = os.path.exists(os.path.join(IMG_DIR, f"{row['molecule']}.png"))
        controls_html.append(control_panel(row, meta, smiles, has_img))
    controls_block = reference_panel() + "\n" + "\n".join(controls_html)

    with open(INDEX_HTML) as f:
        page = f.read()
    page = inject(page, START, END, panels, "candidate panels")
    page = inject(page, CTRL_START, CTRL_END, controls_block, "control panels")
    page = stamp_asset_versions(page)
    with open(INDEX_HTML, "w") as f:
        f.write(page)

    total_kb = len(page.encode()) / 1024
    print(f"Injected into {os.path.relpath(INDEX_HTML, SCRIPT_DIR)}:")
    print(f"  {len(rows)} candidate panels")
    print(f"  {len(controls_html)} control panels + the 9DWV reference")
    print(f"  page is now {total_kb:.0f} KB; 3D served from structures.json via viewer.js")


if __name__ == "__main__":
    main()
